CREATE TABLE withdrawn_member_identity
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    former_member_id BIGINT                                  NOT NULL,
    email_key        VARCHAR(64)                             NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at       TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_withdrawn_member_identity PRIMARY KEY (id),
    CONSTRAINT uk_withdrawn_member_identity_email_member UNIQUE (email_key, former_member_id)
);
