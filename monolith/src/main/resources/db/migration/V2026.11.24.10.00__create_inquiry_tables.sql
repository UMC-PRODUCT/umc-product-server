CREATE TABLE inquiry_category
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name          VARCHAR(50)                             NOT NULL,
    display_order INT                                     NOT NULL,
    active        BOOLEAN                                 NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_inquiry_category PRIMARY KEY (id),
    CONSTRAINT uq_inquiry_category_name UNIQUE (name),
    CONSTRAINT ck_inquiry_category_name
        CHECK (char_length(btrim(name)) BETWEEN 1 AND 50)
);

