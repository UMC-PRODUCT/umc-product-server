CREATE TABLE inquiry
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    author_member_id  BIGINT                                  NOT NULL,
    category_id       BIGINT                                  NOT NULL,
    target_team       VARCHAR(40),
    title             VARCHAR(100)                            NOT NULL,
    status            VARCHAR(20)                             NOT NULL,
    chat_room_id      BIGINT                                  NOT NULL,
    last_message_at   TIMESTAMP WITH TIME ZONE                NOT NULL,
    closed_at         TIMESTAMP WITH TIME ZONE,
    client_request_id UUID                                    NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_inquiry PRIMARY KEY (id),
    CONSTRAINT uq_inquiry_chat_room UNIQUE (chat_room_id),
    CONSTRAINT uq_inquiry_author_client_request UNIQUE (author_member_id, client_request_id),
    CONSTRAINT fk_inquiry_category
        FOREIGN KEY (category_id) REFERENCES inquiry_category (id),
    CONSTRAINT ck_inquiry_positive_ids
        CHECK (author_member_id > 0 AND chat_room_id > 0),
    CONSTRAINT ck_inquiry_title
        CHECK (char_length(btrim(title)) BETWEEN 1 AND 100),
    CONSTRAINT ck_inquiry_status
        CHECK (status IN ('RECEIVED', 'IN_PROGRESS', 'CLOSED')),
    CONSTRAINT ck_inquiry_target_team
        CHECK (target_team IS NULL OR target_team IN (
            'BRAND_GROWTH',
            'LEARNING_ACTIVITY',
            'COMMUNITY_CONNECTION',
            'OPERATIONS_ENABLEMENT',
            'PLATFORM',
            'DESIGN_PLATFORM',
            'INFRASTRUCTURE'
        )),
    CONSTRAINT ck_inquiry_closed_at
        CHECK ((status = 'CLOSED') = (closed_at IS NOT NULL))
);

CREATE INDEX idx_inquiry_author_last_message
    ON inquiry (author_member_id, last_message_at DESC, id DESC);
