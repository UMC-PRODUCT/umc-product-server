CREATE TABLE challenger_deactivation
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    challenger_id           BIGINT                                  NOT NULL,
    status                  VARCHAR(255)                            NOT NULL,
    reason                  VARCHAR(255)                            NOT NULL,
    reason_detail           VARCHAR(100),
    memo                    VARCHAR(100),
    registered_by_member_id BIGINT                                  NOT NULL,
    created_at              TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at              TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_challenger_deactivation PRIMARY KEY (id),
    CONSTRAINT uk_challenger_deactivation_challenger UNIQUE (challenger_id)
);

CREATE TABLE challenger_deactivation_history
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    challenger_deactivation_id BIGINT                                  NOT NULL,
    action                     VARCHAR(255)                            NOT NULL,
    image_count                INTEGER                                 NOT NULL,
    link_count                 INTEGER                                 NOT NULL,
    actor_member_id            BIGINT                                  NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_challenger_deactivation_history PRIMARY KEY (id),
    CONSTRAINT fk_challenger_deactivation_history_deactivation
        FOREIGN KEY (challenger_deactivation_id) REFERENCES challenger_deactivation (id)
);

CREATE TABLE challenger_deactivation_image
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    deactivation_history_id    BIGINT                                  NOT NULL,
    image_id                   VARCHAR(255)                            NOT NULL,
    display_order              INTEGER                                 NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_challenger_deactivation_image PRIMARY KEY (id),
    CONSTRAINT uk_challenger_deactivation_image_history_image
        UNIQUE (deactivation_history_id, image_id),
    CONSTRAINT fk_challenger_deactivation_image_deactivation_history
        FOREIGN KEY (deactivation_history_id) REFERENCES challenger_deactivation_history (id)
);

CREATE TABLE challenger_deactivation_link
(
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    deactivation_history_id    BIGINT                                  NOT NULL,
    link                       VARCHAR(255)                            NOT NULL,
    display_order              INTEGER                                 NOT NULL,
    created_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                 TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_challenger_deactivation_link PRIMARY KEY (id),
    CONSTRAINT uk_challenger_deactivation_link_history_link
        UNIQUE (deactivation_history_id, link),
    CONSTRAINT fk_challenger_deactivation_link_deactivation_history
        FOREIGN KEY (deactivation_history_id) REFERENCES challenger_deactivation_history (id)
);

