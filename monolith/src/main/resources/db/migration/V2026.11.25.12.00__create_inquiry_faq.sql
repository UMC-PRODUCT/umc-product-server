CREATE TABLE inquiry_faq
(
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    status                    VARCHAR(20)                             NOT NULL,
    draft_question            VARCHAR(200)                            NOT NULL,
    draft_answer              TEXT,
    draft_aliases             TEXT[]                                  NOT NULL DEFAULT '{}',
    draft_category_id         BIGINT,
    draft_audience_id         BIGINT,
    draft_end_date            DATE,
    draft_related_faq_id      BIGINT,
    published_question        VARCHAR(200),
    published_answer          TEXT,
    published_aliases         TEXT[],
    published_category_id     BIGINT,
    published_audience_id     BIGINT,
    published_end_date        DATE,
    published_related_faq_id  BIGINT,
    published_search_text     TEXT,
    published_at              TIMESTAMP WITH TIME ZONE,
    published_by_member_id    BIGINT,
    created_by_member_id      BIGINT                                  NOT NULL,
    created_at                TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_inquiry_faq PRIMARY KEY (id),
    CONSTRAINT fk_inquiry_faq_draft_category
        FOREIGN KEY (draft_category_id) REFERENCES inquiry_category (id),
    CONSTRAINT fk_inquiry_faq_draft_audience
        FOREIGN KEY (draft_audience_id) REFERENCES inquiry_faq_audience (id),
    CONSTRAINT fk_inquiry_faq_draft_related
        FOREIGN KEY (draft_related_faq_id) REFERENCES inquiry_faq (id) ON DELETE SET NULL,
    CONSTRAINT fk_inquiry_faq_published_category
        FOREIGN KEY (published_category_id) REFERENCES inquiry_category (id),
    CONSTRAINT fk_inquiry_faq_published_audience
        FOREIGN KEY (published_audience_id) REFERENCES inquiry_faq_audience (id),
    CONSTRAINT fk_inquiry_faq_published_related
        FOREIGN KEY (published_related_faq_id) REFERENCES inquiry_faq (id) ON DELETE SET NULL,
    CONSTRAINT ck_inquiry_faq_status
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),
    CONSTRAINT ck_inquiry_faq_published
        CHECK ((status = 'DRAFT') = (published_at IS NULL)),
    CONSTRAINT ck_inquiry_faq_draft_question
        CHECK (char_length(btrim(draft_question)) BETWEEN 1 AND 200)
);

CREATE INDEX idx_inquiry_faq_status_category ON inquiry_faq (status, published_category_id);

CREATE TABLE inquiry_faq_resolution
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    faq_id     BIGINT                                  NOT NULL,
    member_id  BIGINT                                  NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_inquiry_faq_resolution PRIMARY KEY (id),
    CONSTRAINT uq_inquiry_faq_resolution UNIQUE (faq_id, member_id),
    CONSTRAINT fk_inquiry_faq_resolution_faq
        FOREIGN KEY (faq_id) REFERENCES inquiry_faq (id) ON DELETE CASCADE
);

