CREATE TABLE project_matching_chapter_transfer
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE                NOT NULL,
    gisu_id               BIGINT                                  NOT NULL,
    member_id             BIGINT                                  NOT NULL,
    from_chapter_id       BIGINT                                  NOT NULL,
    to_chapter_id         BIGINT                                  NOT NULL,
    reason                VARCHAR(255),
    created_by_member_id  BIGINT                                  NOT NULL,
    released_at           TIMESTAMP WITH TIME ZONE,
    released_by_member_id BIGINT,
    release_reason        VARCHAR(255),
    CONSTRAINT pk_project_matching_chapter_transfer PRIMARY KEY (id),
    CONSTRAINT ck_project_matching_chapter_transfer_different_chapter CHECK (from_chapter_id <> to_chapter_id)
);

-- 기수·회원당 활성(미해제) 이동은 하나만 허용합니다. 해제된 행은 이력으로 남습니다.
CREATE UNIQUE INDEX uk_project_matching_chapter_transfer_active
    ON project_matching_chapter_transfer (gisu_id, member_id)
    WHERE released_at IS NULL;

-- 지부별 매칭 모집단(통계, 랜덤매칭 후보) 계산용. 지부는 기수에 종속되므로 지부 ID 단독으로 조회합니다.
CREATE INDEX ix_project_matching_chapter_transfer_to_chapter
    ON project_matching_chapter_transfer (to_chapter_id)
    WHERE released_at IS NULL;

CREATE INDEX ix_project_matching_chapter_transfer_from_chapter
    ON project_matching_chapter_transfer (from_chapter_id)
    WHERE released_at IS NULL;
