CREATE TABLE notification_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id UUID NOT NULL,
    member_id BIGINT NOT NULL,
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    image_url TEXT,
    deep_link TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_notification_history_request_member UNIQUE (request_id, member_id)
);

CREATE INDEX idx_notification_history_member_created_id
    ON notification_history (member_id, created_at DESC, id DESC);
