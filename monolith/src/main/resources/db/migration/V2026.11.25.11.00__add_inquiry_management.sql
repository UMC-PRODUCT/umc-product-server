CREATE TABLE inquiry_label_assignment
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    inquiry_id BIGINT                                  NOT NULL,
    label_id   BIGINT                                  NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_inquiry_label_assignment PRIMARY KEY (id),
    CONSTRAINT uq_inquiry_label_assignment UNIQUE (inquiry_id, label_id),
    CONSTRAINT fk_inquiry_label_assignment_inquiry
        FOREIGN KEY (inquiry_id) REFERENCES inquiry (id) ON DELETE CASCADE,
    CONSTRAINT fk_inquiry_label_assignment_label
        FOREIGN KEY (label_id) REFERENCES inquiry_label (id) ON DELETE CASCADE
);

CREATE INDEX idx_inquiry_label_assignment_label ON inquiry_label_assignment (label_id, inquiry_id);

CREATE TABLE inquiry_history
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    inquiry_id                  BIGINT                                  NOT NULL,
    type                        VARCHAR(30)                             NOT NULL,
    actor_member_id             BIGINT                                  NOT NULL,
    previous_assignee_member_id BIGINT,
    new_assignee_member_id      BIGINT,
    previous_team               VARCHAR(40),
    new_team                    VARCHAR(40),
    created_at                  TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at                  TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_inquiry_history PRIMARY KEY (id),
    CONSTRAINT fk_inquiry_history_inquiry
        FOREIGN KEY (inquiry_id) REFERENCES inquiry (id) ON DELETE CASCADE,
    CONSTRAINT ck_inquiry_history_type
        CHECK (type IN ('ASSIGNED', 'REASSIGNED', 'UNASSIGNED', 'TEAM_CHANGED'))
);

CREATE INDEX idx_inquiry_history_inquiry ON inquiry_history (inquiry_id, id);
