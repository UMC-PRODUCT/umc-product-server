CREATE INDEX idx_inquiry_assignee ON inquiry (assignee_member_id);

CREATE TABLE inquiry_label
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name       VARCHAR(30)                             NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_inquiry_label PRIMARY KEY (id),
    CONSTRAINT uq_inquiry_label_name UNIQUE (name),
    CONSTRAINT ck_inquiry_label_name
        CHECK (char_length(btrim(name)) BETWEEN 1 AND 30)
);

