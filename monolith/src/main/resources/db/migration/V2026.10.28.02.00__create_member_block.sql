CREATE TABLE member_block
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    blocker_member_id BIGINT                                  NOT NULL,
    blocked_member_id BIGINT                                  NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE                NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE                NOT NULL,
    CONSTRAINT pk_member_block PRIMARY KEY (id),
    CONSTRAINT uq_member_block_blocker_blocked UNIQUE (blocker_member_id, blocked_member_id),
    CONSTRAINT ck_member_block_not_self
        CHECK (blocker_member_id <> blocked_member_id)
);

CREATE INDEX idx_member_block_blocker
    ON member_block (blocker_member_id);
